"""WatchPlay protocol v0.1 — wire format primitives.

This module is the **normative executable form** of docs/spec/02-wire-format.md.
If this file and the spec ever disagree, the spec wins and this file is the bug.
Every hex dump quoted in the spec is generated by `tools/gen_traces.py`, which
imports this module -- so the docs cannot silently drift.

All integers are little-endian. All structs are packed (no padding).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import IntEnum
from typing import Final

MAGIC: Final[bytes] = b"WP"
PROTOCOL_VERSION: Final[int] = 1
HEADER_SIZE: Final[int] = 16

#: Largest frame header we will ever skip over. Guards against a corrupt
#: `hdr_len` making the parser jump a wild distance.
MAX_HEADER_SIZE: Final[int] = 256


