# --------------------------------------------------------------------------
# Flags (spec 02-wire-format.md section 4)
# --------------------------------------------------------------------------
class Flags(IntEnum):
    ACK_REQUIRED = 0x0001
    RETRANSMIT = 0x0002
    LAST_IN_BURST = 0x0004
    IDLE_HINT = 0x0008
    # -- video-only ------------------------------------------------
    KEYFRAME = 0x0008
    FIRST_CHUNK = 0x0010
    LAST_CHUNK = 0x0020
    DISCONTINUITY = 0x0040
