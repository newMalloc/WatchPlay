"""Generate the launcher icons of every Android app in this repository.

Not part of the Gradle build: run it by hand when the artwork changes, and commit
what it writes. It is the only script in the repository that needs Pillow.

    python android/art/make_launcher_icons.py

The artwork is a rounded blue/green tile carrying a watch on a phone. Three
measurements drive everything else and are taken from that file:

    TILE     the tile's bounding box, measured on the 2048 px source
    CORNER   its corner radius (161 per mille of the side, the iOS squircle ratio)
    CROP     the square both adaptive layers are cut from

CROP is the load-bearing number. An adaptive icon paints a 108 x 108 dp canvas
but every launcher masks it to the inscribed 72 dp circle, so the tile is sized
against that mask and not against the canvas: at CROP = 2020 px the tile lands
at 75 dp, the mask trims 1.7 dp off each of its edges, and the artwork keeps the
proportions it was drawn with - watch 54 % of the tile, 41 dp across, the phone
and both strap ends inside the frame. Cropping tighter magnifies the artwork and
cuts the phone out of frame.

The ground inside the tile's rounded corners is cut away, so a squircle mask
shows the background layer instead of a paler seam.
"""

from __future__ import annotations

import pathlib

from PIL import Image, ImageDraw

ANDROID = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ANDROID / "art/launcher-icon-source.jpg"

# Both apps are WatchPlay, and the icon is the product: the phone-side demo and
# the watch-side sink carry the same one.
MODULES = ("demo", "sink")

TILE = (305, 305, 1715, 1745)
CORNER = 230
CROP = 2020
# Both adaptive layers are square; the round legacy icon has to hide the pale
# ground entirely, which needs a crop narrower than CROP.
ROUND_CROP = 1380

# Sampled just outside the tile, so the background continues the artwork's own
# ground instead of inventing a colour.
BACKGROUND = ((212, 233, 254), (212, 234, 255), (237, 254, 244), (237, 254, 244))

DENSITIES = {"mdpi": 1.0, "hdpi": 1.5, "xhdpi": 2.0, "xxhdpi": 3.0, "xxxhdpi": 4.0}

# Legacy (pre-adaptive) icons are 48 dp at mdpi. minSdk is 26, so the adaptive
# XML is what every device actually draws; these exist for icon extractors.
LEGACY_DP = 48

ADAPTIVE_LAYERS = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by android/art/make_launcher_icons.py; edit the script, not this file. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
"""


def source() -> Image.Image:
    return Image.open(SOURCE).convert("RGB")


def centre_crop(image: Image.Image, side: int) -> Image.Image:
    left, top, right, bottom = TILE
    x, y = (left + right) // 2, (top + bottom) // 2
    return image.crop((x - side // 2, y - side // 2, x + side // 2, y + side // 2))


def tile_alpha(size: int, frame: int = CROP) -> Image.Image:
    """Alpha for a square frame: the tile's rounded rectangle, pale ground excluded."""
    scale = size / frame
    left, top, right, bottom = TILE
    x, y = (left + right) // 2, (top + bottom) // 2
    inset = 4 * scale  # the artwork's own edge is soft; stay inside it
    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle(
        (
            (left - (x - frame // 2)) * scale + inset,
            (top - (y - frame // 2)) * scale + inset,
            (right - (x - frame // 2)) * scale - inset,
            (bottom - (y - frame // 2)) * scale - inset,
        ),
        radius=CORNER * scale,
        fill=255,
    )
    return mask


def ground(size: int) -> Image.Image:
    corners = Image.new("RGB", (2, 2))
    corners.putpixel((0, 0), BACKGROUND[0])
    corners.putpixel((1, 0), BACKGROUND[1])
    corners.putpixel((0, 1), BACKGROUND[2])
    corners.putpixel((1, 1), BACKGROUND[3])
    return corners.resize((size, size), Image.BILINEAR)


def circle(size: int) -> Image.Image:
    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, size - 1, size - 1), fill=255)
    return mask


def images() -> list[tuple[str, str, Image.Image]]:
    art = source()
    square = centre_crop(art, CROP)
    out: list[tuple[str, str, Image.Image]] = []

    for folder, factor in DENSITIES.items():
        adaptive = round(108 * factor)

        foreground = square.resize((adaptive, adaptive), Image.LANCZOS).convert("RGBA")
        foreground.putalpha(tile_alpha(adaptive))
        out.append((f"drawable-{folder}", "ic_launcher_foreground.png", foreground))
        out.append((f"drawable-{folder}", "ic_launcher_background.png", ground(adaptive)))

        legacy = round(LEGACY_DP * factor)
        flat = square.resize((legacy, legacy), Image.LANCZOS).convert("RGBA")
        flat.putalpha(tile_alpha(legacy))
        out.append((f"mipmap-{folder}", "ic_launcher.png", flat))

        disc = centre_crop(art, ROUND_CROP).resize((legacy, legacy), Image.LANCZOS).convert("RGBA")
        disc.putalpha(circle(legacy))
        out.append((f"mipmap-{folder}", "ic_launcher_round.png", disc))
    return out


def main() -> None:
    layers = images()
    for module in MODULES:
        res = ANDROID / module / "src/main/res"
        print(f"{module}: {len(layers)} PNGs + 2 XML")
        for folder, name, image in layers:
            target = res / folder
            target.mkdir(parents=True, exist_ok=True)
            image.save(target / name, optimize=True)
        anydpi = res / "mipmap-anydpi-v26"
        anydpi.mkdir(parents=True, exist_ok=True)
        for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
            (anydpi / name).write_text(ADAPTIVE_LAYERS, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
